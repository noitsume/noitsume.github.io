/* eslint-disable @typescript-eslint/no-unused-expressions */
// Run with Playwright CLI run-code --filename. Requires the development fixture.
async page => {
  const checks=[];
  const verify=(value,name)=>{if(!value)throw Error(name); checks.push(name);};
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.goto('http://localhost:3000/dev/aura');
  await page.setViewportSize({width:1440,height:900});
  await page.locator('canvas').waitFor();
  await page.waitForTimeout(500);
  await page.evaluate(()=>{window.addEventListener('kenangin:three-context',e=>window.__auraQAContext=e.detail,{once:true});window.dispatchEvent(new Event('kenangin:inspect-three'));});
  const time=()=>page.evaluate(()=>window.__auraQAContext.scene.children[0].material.uniforms.uTime.value);
  const renderState=()=>page.evaluate(()=>{
    const {scene,renderer}=window.__auraQAContext;
    const u=scene.children[0].material.uniforms;
    return JSON.stringify([renderer.info.render.frame,...['uTime','uOpen','uSpread','uTurn','uAccent','uFront','uBack','uWorld'].map(key=>u[key].value)]);
  });
  const verifyFrozen=async name=>{await page.waitForTimeout(300);const state=await renderState();await page.waitForTimeout(600);verify(await renderState()===state,name);};
  const before=await time(); await page.waitForTimeout(300);
  verify(await time()===before,'Aura stays still before music starts');
  await page.getByRole('button',{name:'Buka kejutan'}).click();
  await page.waitForTimeout(1400);
  verify(await page.locator('main').getAttribute('data-playback-ready')==='true','opening settles');
  verify(Number(await page.locator('main').evaluate(e=>e.style.getPropertyValue('--aura-open')))>.99,'DOM aperture and shader finish together');
  const playingTime=await time(); await page.waitForTimeout(300);
  verify(await time()>playingTime&&await page.evaluate(()=>window.__auraQAContext.scene.children[0].material.uniforms.uBack.value>0),'playing music drives ambient clock and beatmap signal');
  await page.screenshot({path:'tmp/aura-verified-desktop.png'});
  await page.getByRole('button',{name:'Lanjut →'}).click(); await page.waitForTimeout(900);
  verify(await page.locator('main').getAttribute('data-focused-section')==='section_portrait','portrait navigation');
  verify(await page.locator('audio[data-audio-layer=section]').evaluate(e=>!e.paused&&e.currentTime>0),'section music starts after settle');
  verify(await page.locator('main').evaluate(e=>Number(e.style.getPropertyValue('--beat'))>0),'section beatmap drives foreground accent');
  await page.getByRole('button',{name:'♫ Musik aktif'}).click();
  verify(await page.locator('audio').evaluateAll(a=>a.every(e=>e.paused)),'music pause stops both transports');
  await verifyFrozen('music pause stops all Aura uniforms and render while motion preference stays on');
  verify(await page.locator('main').getAttribute('data-motion')==='on'&&await page.locator('main').getAttribute('data-aura-motion')==='off','music pause preserves motion preference');
  verify(await page.locator('main').evaluate(e=>Number(e.style.getPropertyValue('--beat'))===0&&Number(e.style.getPropertyValue('--background-signal'))===0),'music pause clears signals');
  await page.getByRole('button',{name:'Jeda gerakan'}).click();
  await page.getByRole('button',{name:'♪ Musik dijeda'}).click();
  await verifyFrozen('resuming music respects explicit motion pause');
  await page.getByRole('button',{name:'Aktifkan gerakan'}).click(); await page.waitForTimeout(500);
  const resumedTime=await time(); await page.waitForTimeout(300);
  verify(await time()>resumedTime,'Aura resumes when music and motion are both active');
  verify(await page.evaluate(()=>window.__auraQAContext.scene.children[0].material.uniforms.uAccent.value===0),'resuming playback does not replay the section entrance accent');
  await page.locator('audio').evaluateAll(a=>a.forEach(e=>e.pause()));
  await verifyFrozen('actual audio pause stops Aura even when music control is enabled');
  await page.locator('audio').evaluateAll(a=>Promise.all(a.filter(e=>e.getAttribute('src')).map(e=>e.play())));
  await page.waitForTimeout(500);
  await page.locator('audio').evaluateAll(a=>a.forEach(e=>{e.muted=true;}));
  await verifyFrozen('muted audio stops Aura');
  await page.locator('audio').evaluateAll(a=>a.forEach(e=>{e.muted=false;}));
  await page.waitForTimeout(500);
  await page.locator('audio').evaluateAll(a=>a.forEach(e=>e.dispatchEvent(new Event('waiting'))));
  await verifyFrozen('waiting audio events stop Aura');
  await page.locator('audio').evaluateAll(a=>a.forEach(e=>e.dispatchEvent(new Event('playing'))));
  await page.waitForTimeout(500);
  await page.getByRole('button',{name:'Lanjut →'}).click(); await page.waitForTimeout(900);
  verify(await page.locator('.is-active video').evaluate(e=>!e.paused&&e.currentTime>0),'video starts after settle');
  await page.getByRole('button',{name:'Lanjut →'}).click(); await page.waitForTimeout(700);
  verify(await page.locator('video').evaluateAll(v=>v.every(e=>e.paused)),'departed video is paused');
  const content=page.locator('.receiver-slide.is-active [data-section-content]');
  await content.hover(); await page.mouse.wheel(0,450); await page.waitForTimeout(250);
  verify(await page.locator('main').getAttribute('data-focused-section')==='section_letter'&&await content.evaluate(e=>e.scrollTop)>0,'long letter scroll reserves navigation');
  await page.getByRole('button',{name:'Jeda gerakan'}).click(); await page.waitForTimeout(400);
  const frozen=await time(); const frame=await page.evaluate(()=>window.__auraQAContext.renderer.info.render.frame);
  await page.waitForTimeout(600);
  verify(await time()===frozen && await page.evaluate(()=>window.__auraQAContext.renderer.info.render.frame)===frame,'pause stops ambient clock and continuous render');
  await page.getByRole('button',{name:'Aktifkan gerakan'}).click();
  for(let i=0;i<15;i++){
    await page.getByRole('button',{name:'← Kembali'}).click(); await page.waitForTimeout(470);
    await page.getByRole('button',{name:'Lanjut →'}).click(); await page.waitForTimeout(470);
  }
  verify(await page.evaluate(()=>window.__auraQAContext.renderer.info.memory.geometries===1&&window.__auraQAContext.renderer.info.memory.textures===0),'30 moves retain one geometry and no media textures');
  await page.getByRole('button',{name:'← Kembali'}).click();
  await page.waitForTimeout(50); await page.getByRole('button',{name:'Lanjut →'}).click(); await page.waitForTimeout(650);
  verify(await page.locator('main').getAttribute('data-focused-section')==='section_letter'&&await page.locator('main').getAttribute('data-playback-ready')==='true','rapid reversal settles latest destination');
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(400); await page.screenshot({path:'tmp/aura-verified-mobile.png'});
  verify(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile has no horizontal document overflow');
  await page.emulateMedia({reducedMotion:'reduce'}); await page.waitForTimeout(500);
  verify(await page.locator('main').getAttribute('data-motion')==='off','reduced motion respected');
  await page.evaluate(()=>window.__auraQAContext.renderer.getContext().getExtension('WEBGL_lose_context').loseContext());
  await page.waitForTimeout(600);
  verify(await page.locator('.aura-environment').getAttribute('data-renderer')==='static','context loss gives static fallback');
  await page.getByRole('button',{name:'Lanjut →'}).click(); await page.waitForTimeout(200);
  await page.getByRole('button',{name:/01 Teman/}).click();
  verify(await page.getByRole('dialog').isVisible(),'wish content remains accessible after GPU loss');
  await page.keyboard.press('Escape');
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.goto('http://localhost:3000/dev/aura?silent=1');
  await page.locator('canvas').waitFor(); await page.waitForTimeout(500);
  await page.evaluate(()=>{window.addEventListener('kenangin:three-context',e=>window.__auraQAContext=e.detail,{once:true});window.dispatchEvent(new Event('kenangin:inspect-three'));});
  await page.getByRole('button',{name:'Buka kejutan'}).click();
  await verifyFrozen('receiver without music keeps Aura static');
  await page.getByRole('button',{name:'Lanjut →'}).click(); await page.waitForTimeout(600);
  verify(await page.locator('main').getAttribute('data-focused-section')==='section_portrait'&&Number(await page.locator('main').evaluate(e=>e.style.getPropertyValue('--aura-open')))>.99,'silent receiver navigation stays usable');
  await page.route('**/dev/aura/assets/music-*',route=>route.abort());
  await page.goto('http://localhost:3000/dev/aura');
  await page.locator('canvas').waitFor(); await page.waitForTimeout(500);
  await page.evaluate(()=>{window.addEventListener('kenangin:three-context',e=>window.__auraQAContext=e.detail,{once:true});window.dispatchEvent(new Event('kenangin:inspect-three'));});
  await page.getByRole('button',{name:'Buka kejutan'}).click(); await page.waitForTimeout(1500);
  await verifyFrozen('failed music leaves Aura static');
  verify(await page.getByRole('button',{name:'♪ Coba musik'}).isVisible()&&Number(await page.locator('main').evaluate(e=>e.style.getPropertyValue('--aura-open')))>.99,'failed music keeps retry and opened content accessible');
  await page.unroute('**/dev/aura/assets/music-*');
  await page.goto('http://localhost:3000/dev/aura?legacy=1&silent=1');
  verify(await page.locator('main').getAttribute('data-renderer-version')==='legacy'&&await page.locator('canvas').count()===0,'legacy snapshot keeps original renderer');
  await page.evaluate(checks=>{window.__auraQAResults=checks;},checks);
}
